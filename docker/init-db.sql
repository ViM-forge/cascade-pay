\getenv payments_password PAYMENTS_DB_PASSWORD
\getenv mock_a_password MOCK_A_DB_PASSWORD
\getenv mock_b_password MOCK_B_DB_PASSWORD
CREATE ROLE payments LOGIN PASSWORD :'payments_password';
CREATE ROLE mock_a LOGIN PASSWORD :'mock_a_password';
CREATE ROLE mock_b LOGIN PASSWORD :'mock_b_password';
CREATE DATABASE payments OWNER payments;
CREATE DATABASE mock_a OWNER mock_a;
CREATE DATABASE mock_b OWNER mock_b;
REVOKE CONNECT, TEMPORARY ON DATABASE payments FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE mock_a FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE mock_b FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE payments TO payments;
GRANT CONNECT, TEMPORARY ON DATABASE mock_a TO mock_a;
GRANT CONNECT, TEMPORARY ON DATABASE mock_b TO mock_b;
REVOKE CONNECT, TEMPORARY ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE template1 FROM PUBLIC;
